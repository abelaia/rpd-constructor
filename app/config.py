"""Настройки приложения: всё, что раньше было «зашито» прямо в код генерации.

Пока вуз один, но данные о нём лежат отдельно от логики: чтобы поддержать
другой вуз, достаточно будет описать ещё один объект University.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class University:
    """Реквизиты вуза для титульного листа.

    dataclass — короткий способ описать класс, который просто хранит данные.
    frozen=True запрещает менять поля после создания (защита от случайной правки).
    """

    ministry: str
    full_name: str
    short_name: str


SFEDU = University(
    ministry="МИНОБРНАУКИ РОССИИ",
    full_name=(
        "Федеральное государственное автономное образовательное\n"
        "учреждение высшего образования «Южный федеральный университет»"
    ),
    short_name="ЮЖНЫЙ ФЕДЕРАЛЬНЫЙ УНИВЕРСИТЕТ",
)

# Вуз, для которого сейчас формируются документы.
UNIVERSITY = SFEDU
